<h2 id="orfao-empresa">Tipo 1 — Órfão da empresa instaladora</h2>

<p>Esse é o caso mais comum. A empresa que instalou o sistema simplesmente para de existir. Pode ser que fechou, mudou de ramo, foi vendida, ou faliu. O sistema continua produzindo energia — porque painéis e inversores são robustos — mas no dia que um componente falhar, o cliente fica sozinho.</p>

<p>O problema cresce especialmente em cidades onde a guerra de preços é agressiva. Mercado solar brasileiro tem uma referência clara da Agner — consultoria especializada que mapeia o setor — sobre faixas de preço justas pra instalação. Quando uma empresa cobra metade dessa referência pra "ganhar a proposta", duas coisas acontecem ao mesmo tempo:</p>

<ul>
  <li>O cliente acha que está fazendo bom negócio</li>
  <li>A empresa não está cobrando o suficiente pra sobreviver os 25 anos de vida útil que prometeu</li>
</ul>

<p>Essa empresa instala bem o suficiente pra entregar e receber. Mas não tem caixa pra manter equipe técnica, pra responder WhatsApp 3 anos depois, pra acionar garantia de fabricante quando inversor falha. Quando o problema aparece — sempre depois de 24 a 48 meses — o cliente liga e ninguém atende.</p>

<p>O mecanismo é cruel porque o cliente nunca conecta a causa com o efeito. Ele acha que "deu azar" com a empresa que sumiu. Não percebe que o preço metade do mercado <em>já era o aviso</em> de que essa empresa não tinha estrutura pra sustentar o serviço.</p>

<h2 id="orfao-tecnologia">Tipo 2 — Órfão da tecnologia</h2>

<p>O segundo tipo é mais técnico, e quase nunca discutido durante a venda. Tecnologia de painel solar evolui rapidamente. Em 5 anos, o que era ponta vira obsoleto. Painel de 330W vendido em 2020 hoje é peça de museu — o padrão atual já passou de 600W por módulo.</p>

<p>Isso impacta o cliente em três cenários:</p>

<ol>
  <li><strong>Substituição de painel queimado:</strong> se um dos 12 painéis falhar no ano 6, encontrar reposição da mesma marca/modelo/wattagem fica difícil. O fabricante pode ter descontinuado a linha. Trocar por modelo diferente desbalanceia o sistema.</li>
  <li><strong>Expansão futura:</strong> querer adicionar 2-3 painéis pra cobrir o carro elétrico que tu vai comprar em 2028 — se o modelo original já não existe mais, a integração fica complicada (microinversor compatível, estrutura compatível, etc).</li>
  <li><strong>Manutenção do inversor:</strong> mesma lógica se aplica. Inversor com vida útil de 8-12 anos vai precisar ser substituído. Se o modelo original saiu de linha, o substituto pode não bater com a configuração instalada.</li>
</ol>

<p>Cliente órfão da tecnologia geralmente descobre o problema só quando precisa fazer reposição. Aí descobre que o "kit completo" que comprou em 2022 não tem mais peças disponíveis no mercado de 2027.</p>

<h2 id="por-que-acontece">Por que o mercado produz órfãos em escala</h2>

<p>A combinação de fatores cria uma armadilha estrutural:</p>

<p>O cliente final compara orçamentos olhando primeiro o preço. Empresas honestas que cobram preço justo pra entregar 25 anos de serviço perdem proposta pra concorrente que cobra metade. A empresa de preço justo perde mercado; a empresa que cobra metade fatura, mas não consegue sustentar operação. Em 3-4 anos, a empresa barata fecha. Os clientes dela viram órfãos. Os clientes da empresa honesta também sofrem — porque ela também fecha, sem mercado pra sustentar a operação correta.</p>

<p>Isso não é teoria. A pesquisa Agner do primeiro semestre de 2022 já mostrava o problema acontecendo em escala nacional. O setor solar residencial brasileiro tem rotatividade alta de empresas instaladoras — muito acima da média de outros setores de engenharia civil.</p>

<h2 id="como-evitar">Como reconhecer uma empresa que vai produzir órfão</h2>

<p>Quatro perguntas pra fazer pro vendedor — em escrito, no WhatsApp, com print salvo — antes de assinar:</p>

<ol>
  <li><strong>"Pode me passar contato de 3 clientes que vocês instalaram há pelo menos 3 anos?"</strong> Empresa que entregou em 2022 e ainda atende em 2026 tem perfil de sobreviver. Empresa que só tem clientes recentes tem perfil de descontinuação.</li>
  <li><strong>"Qual o custo médio de manutenção anual de um sistema instalado por vocês?"</strong> Empresa que responde "manutenção solar é zero" está mentindo — limpeza, troca de fusíveis, vistorias periódicas têm custo. Quem entrega 25 anos cobra manutenção; quem não cobra não vai estar lá.</li>
  <li><strong>"Como vocês acionam garantia de fabricante quando equipamento falha?"</strong> Resposta com nome de pessoa (representante regional) e prazo médio (dias úteis) é sinal de empresa estruturada. Resposta vaga ("a gente resolve") é sinal de improviso.</li>
