<p>Não é que crença não tenha lugar nenhum em solar residencial. Cabe depois da decisão técnica. Tu comprou sistema bem dimensionado, com equipamento de qualidade comprovada, instalado por empresa com responsabilidade técnica. Vai durar 25 anos. Vai te entregar economia mês a mês.</p>

